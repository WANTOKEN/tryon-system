export const languages = [
  { code: 'zh-CN', name: '简体中文', flag: '🇨🇳' },
  { code: 'zh-HK', name: '繁體中文', flag: '🇭🇰' },
  { code: 'en-US', name: 'English', flag: '🇺🇸' },
]

const I18nContext = createContext(null)

export function I18nProvider({ children, initialLang = 'zh-CN' }) {
  const [locale, setLocale] = useState(() => {
    const stored = localStorage.getItem(STORAGE_KEYS.LOCALE)
    if (stored && translations[stored]) {
      return stored
    }
    const browserLang = navigator.language
    if (translations[browserLang]) {
      return browserLang
    }
    if (browserLang.startsWith('zh')) {
      if (browserLang === 'zh-HK' || browserLang === 'zh-TW' || browserLang === 'zh-MO') {
        return 'zh-HK'
      }
      return 'zh-CN'
    }
    return initialLang
  })

  const changeLocale = useCallback(newLocale => {
    if (translations[newLocale]) {
      setLocale(newLocale)
      localStorage.setItem(STORAGE_KEYS.LOCALE, newLocale)
      document.documentElement.lang = newLocale
    }
  }, [])

  const t = useCallback(
    (key, params = {}) => {
      const dict = translations[locale] || translations['zh-CN']
      let text = dict[key] || translations['zh-CN'][key] || key

      Object.entries(params).forEach(([k, v]) => {
        text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
      })

      return text
    },
    [locale]
  )

  const value = useMemo(
    () => ({
      locale,
      changeLocale,
      t,
      currentLang: languages.find(l => l.code === locale) || languages[0],
      languages,
    }),
    [locale, changeLocale, t]
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const context = useContext(I18nContext)
  if (!context) {
    return {
      locale: 'zh-CN',
      changeLocale: () => {},
      t: (key, params = {}) => {
        const dict = translations['zh-CN']
        let text = dict[key] || key
        Object.entries(params).forEach(([k, v]) => {
          text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
        })
        return text
      },
      currentLang: languages[0],
      languages,
    }
  }
  return context
}

export default useI18n
